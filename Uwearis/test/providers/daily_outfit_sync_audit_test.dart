// Audit (P1-2): which outfitsProvider changes make dailyOutfitProvider
// re-read today's plan (GET /daily_outfits/{today}), and which of those
// are needed. Backend candidates for a new plan: every completed `general`
// outfit with an image — every version, not just a group's card. A day
// that already has a plan is only read, never regenerated by the app.
// Skipped tests state the request count that should hold and reproduce a
// finding; run them with --run-skipped.

Future<void> _settle() async {
  for (var i = 0; i < 10; i++) {
    await Future<void>.delayed(Duration.zero);
  }
}

Map<String, dynamic> _outfitJson(
  int id, {
  required int groupId,
  bool fav = false,
  String key = 'k1',
  List<String> seasons = const [],
}) => {
  'outfit_id': id,
  'group_id': groupId,
  'group_type': 'general',
  'status': 'completed',
  'garment_ids': <int>[],
  'result_image_url': 'https://img/$id',
  'result_image_cache_key': '$id-$key',
  'season': seasons,
  'style': <String>[],
  'is_favorite': fav,
};

/// `/outfit` + `/daily_outfits`. [groups]: group id → its versions (first =
/// card). [plan]: today's picked outfit ids (empty = no plan); deleting an
/// outfit removes it from the plan, as the backend's cascade does.
class _Backend {
  final Map<int, List<Map<String, dynamic>>> groups = {};
  List<int> plan = [];
  int dailyGets = 0;
  int generates = 0;

  /// Generate picks these when enough candidates exist, else 422.
  int minCandidates = 1;

  /// Daily GETs wait for [releaseDaily] while set.
  bool holdDaily = false;
  final List<Completer<void>> _heldDaily = [];

  String token = 'A';

  /// Accounts whose day has no plan yet.
  final Set<String> emptyPlanFor = {};

  /// The next daily GET answers 503 (decided when it arrives).
  bool failNextDaily = false;

  /// The account (by its access token) behind each generate.
  final List<String> generatedBy = [];

  /// Generates wait for the test while set (decided when they arrive).
  bool holdGenerate = false;
  final List<Completer<void>> heldGenerates = [];

  int regenerates = 0;
  bool holdRegenerate = false;
  final List<Completer<void>> heldRegenerates = [];

  Iterable<Map<String, dynamic>> get _allOutfits =>
      groups.values.expand((v) => v);

  Map<String, dynamic>? _outfit(int id) {
    for (final o in _allOutfits) {
      if (o['outfit_id'] == id) return o;
    }
    return null;
  }

  Future<void> releaseDaily() async {
    holdDaily = false;
    for (final g in [..._heldDaily]) {
      g.complete();
    }
    _heldDaily.clear();
    await _settle();
  }

  late final MockClient client = MockClient((request) async {
    final path = request.url.path;
    if (path.contains('/daily_outfits/generate')) {
      generates++;
      generatedBy.add(request.headers['Authorization'] ?? '');
      final candidates = _allOutfits.map((o) => o['outfit_id'] as int).toList();
      final enough = candidates.length >= minCandidates;
      if (holdGenerate) {
        final gate = Completer<void>();
        heldGenerates.add(gate);
        await gate.future;
      }
      if (!enough) {
        return jsonResponse({
          'success': false,
          'message': 'not enough',
          'data': null,
          'error_code': 'INSUFFICIENT_OUTFIT_DATA',
        }, status: 422);
      }
      plan = candidates.take(1).toList();
      return jsonResponse(
        envelope({
          'id': 1,
          'outfits': [for (final id in plan) _outfit(id)],
        }),
      );
    }
    if (path.contains('/daily_outfits/')) {
      dailyGets++;
      final planned = [
        if (!emptyPlanFor.contains(token))
          for (final id in plan)
            if (_outfit(id) case final o?) {...o, 'name': '$token-plan'},
      ];
      final fails = failNextDaily;
      failNextDaily = false;
      if (holdDaily) {
        final gate = Completer<void>();
        _heldDaily.add(gate);
        await gate.future;
      }
      if (fails) {
        return jsonResponse({
          'success': false,
          'message': 'boom',
          'data': null,
          'error_code': 'SERVICE_UNAVAILABLE',
        }, status: 503);
      }
      return jsonResponse(
        envelope(planned.isEmpty ? null : {'outfits': planned}),
      );
    }
    if (request.method == 'DELETE') {
      final segs = request.url.pathSegments;
      final i = segs.indexOf('outfit');
      final groupId = int.parse(segs[i + 1]);
      if (segs.length == i + 2) {
        final removed = groups.remove(groupId) ?? const [];
        plan.removeWhere((id) => removed.any((o) => o['outfit_id'] == id));
      } else {
        final outfitId = int.parse(segs[i + 2]);
        groups[groupId]?.removeWhere((o) => o['outfit_id'] == outfitId);
        plan.remove(outfitId);
      }
      return jsonResponse(envelope(null));
    }
    if (request.method == 'POST' && path.endsWith('/regenerate')) {
      regenerates++;
      final segs = request.url.pathSegments;
      final i = segs.indexOf('outfit');
      final groupId = int.parse(segs[i + 1]);
      final outfitId = int.parse(segs[i + 2]);
      final versions = groups[groupId]!;
      final at = versions.indexWhere((o) => o['outfit_id'] == outfitId);
      versions[at] = _outfitJson(
        outfitId,
        groupId: groupId,
        key: 'r$regenerates',
      );
      if (holdRegenerate) {
        final gate = Completer<void>();
        heldRegenerates.add(gate);
        await gate.future;
      }
      return jsonResponse(envelope(versions[at]));
    }
    if (request.method == 'POST' && path.endsWith('/generate')) {
      final segs = request.url.pathSegments;
      final groupId = int.parse(segs[segs.indexOf('outfit') + 1]);
      final id = 500 + _allOutfits.length;
      final created = _outfitJson(id, groupId: groupId);
      (groups[groupId] ??= []).add(created);
      return jsonResponse(envelope(created));
    }
    // GET /outfit: one item per group, its first version as the card.
    return jsonResponse(
      envelope({
        'items': [
          for (final e in groups.entries)
            {
              'group_id': e.key,
              'name': null,
              'cover_outfit_id': e.value.first['outfit_id'],
              'outfits': e.value,
            },
        ],
        'total': groups.length,
        'page': 1,
      }),
    );
  });
}

void main() {
  late _Backend backend;
  late ProviderContainer container;

  setUp(() {
    setUpFakeAuth(accessToken: 'token-a');
    backend = _Backend()
      ..groups[1] = [
        _outfitJson(1, groupId: 1),
        _outfitJson(11, groupId: 1), // a non-card version
      ]
      ..groups[2] = [_outfitJson(2, groupId: 2)]
      ..plan = [1, 11];
  });

  Future<void> run(Future<void> Function() body) {
    return http.runWithClient(() async {
      container = ProviderContainer();
      addTearDown(container.dispose);
      container.listen(outfitsProvider, (_, _) {});
      container.listen(dailyOutfitProvider, (_, _) {});
      await container.read(outfitsProvider.future);
      await container.read(dailyOutfitProvider.future);
      await _settle();
      await body();
    }, () => backend.client);
  }

  OutfitsNotifier outfits() => container.read(outfitsProvider.notifier);

  /// Answers every held daily GET (follow-ups included) until none is left.
  Future<void> answerAll() async {
    while (backend._heldDaily.isNotEmpty) {
      backend._heldDaily.removeAt(0).complete();
      await _settle();
    }
  }

  List<int> daily() =>
      container.read(dailyOutfitProvider).value!.map((o) => o.id).toList();

  /// Daily GETs caused by [action] alone.
  Future<int> dailyGetsDuring(Future<void> Function() action) async {
    final before = backend.dailyGets;
    await action();
    await _settle();
    return backend.dailyGets - before;
  }

  group('syncs that must stay', () {
    test('deleting an outfit in today\'s plan re-reads it', () {
      return run(() async {
        await OutfitService().deleteGroup(1);
        outfits().removeGroup(1);
        await _settle();

        expect(daily(), isNot(contains(1)));
      });
    });

    test("deleting a non-card version in today's plan re-reads it (the "
        "card list doesn't change)", () {
      return run(() async {
        await OutfitService().deleteOutfit(1, 11);
        outfits().removeOutfitVersion(11); // what Outfit Details does
        await _settle();

        expect(daily(), [1]);
      });
    });

    test('a day with too few outfits gets a plan once a new outfit lands', () {
      backend
        ..plan = []
        ..groups.remove(2)
        ..minCandidates = 3; // 2 candidates: insufficient
      return run(() async {
        expect(daily(), isEmpty);
        final generatesBefore = backend.generates;

        backend.minCandidates = 3;
        await OutfitService().generateOutfit(garmentIds: [1, 2], groupId: 3);
        await outfits().refresh(); // Create Outfit refreshes after a render
        await _settle();

        expect(backend.generates, greaterThan(generatesBefore));
        expect(daily(), isNotEmpty);
      });
    });

    test('regenerating the card outfit in the plan brings its new image to '
        'today\'s card', () {
      return run(() async {
        backend.groups[1]![0] = _outfitJson(1, groupId: 1, key: 'k2');
        await outfits().refresh(); // what Outfit Details does after it
        await _settle();

        final o = container.read(dailyOutfitProvider).value!.first;
        expect(o.resultImageCacheKey, '1-k2');
      });
    });

    test("regenerating a non-card version in the plan brings its new image "
        "to today's card", () {
      return run(() async {
        // What Outfit Details does: the regenerate request, then a refresh
        // (which can't show a non-card version's new image by itself).
        await OutfitService().regenerateOutfit(1, 11);
        await outfits().refresh();
        await _settle();

        final o = container
            .read(dailyOutfitProvider)
            .value!
            .firstWhere((o) => o.id == 11);
        expect(o.resultImageCacheKey, '11-r1');
      });
    });
  });

  group('requests that are not needed', () {
    test('favoriting an outfit elsewhere (Outfit Details / Home fallback)', () {
      return run(() async {
        final gets = await dailyGetsDuring(
          () async => outfits().updateOutfitFavorite(2, isFavorite: true),
        );
        expect(gets, 0);
      });
    });

    test("favoriting from today's own card (its outfits sync)", () {
      return run(() async {
        final today = container.read(dailyOutfitProvider).value!.first;
        final gets = await dailyGetsDuring(
          () => container
              .read(dailyOutfitProvider.notifier)
              .toggleOutfitFavorite(today),
        );
        expect(gets, 0);
      });
    });

    test('editing tags', () {
      return run(() async {
        final gets = await dailyGetsDuring(
          () async => outfits().updateOutfitTags(
            2,
            style: ['Casual'],
            suitableTemperature: (
              minC: 18,
              maxC: 27,
              source: OutfitTemperatureSource.manual,
            ),
          ),
        );
        expect(gets, 0);
      });
    });

    test('renaming a group', () {
      return run(() async {
        final gets = await dailyGetsDuring(
          () async => outfits().updateGroupName(2, name: 'Weekend'),
        );
        expect(gets, 0);
      });
    });

    test('a refresh that brings back the same outfits', () {
      return run(() async {
        final gets = await dailyGetsDuring(() => outfits().refresh());
        expect(gets, 0);
      });
    });

    test('a refresh that only re-signs image URLs (same cache keys)', () {
      return run(() async {
        for (final versions in backend.groups.values) {
          for (final o in versions) {
            o['result_image_url'] = '${o['result_image_url']}?resigned';
          }
        }
        final gets = await dailyGetsDuring(() => outfits().refresh());
        expect(gets, 0);
      });
    });

    // Accepted cost, not a loosened check: the delete's garmentLinkChanges
    // carries no id, and it is what keeps a non-card version deleted from
    // today's plan in sync (see "syncs that must stay"). So deleting an
    // outfit that isn't in the plan costs exactly one re-read — one, not the
    // former one per outfitsProvider change.
    test('deleting an outfit that is not in the plan costs exactly one '
        're-read (accepted)', () {
      return run(() async {
        final gets = await dailyGetsDuring(() async {
          await OutfitService().deleteGroup(2);
          outfits().removeGroup(2); // what Outfit Details does
        });
        expect(gets, 1);
      });
    });
  });

  group('bursts and isolation', () {
    test('several changes in a row coalesce into at most two re-reads', () {
      return run(() async {
        backend.holdDaily = true;
        final gets = await dailyGetsDuring(() async {
          outfits()
            ..updateOutfitFavorite(2, isFavorite: true)
            ..updateOutfitFavorite(2, isFavorite: false)
            ..updateGroupName(2, name: 'A')
            ..updateGroupName(2, name: 'B');
          await _settle();
          await backend.releaseDaily();
        });
        expect(gets, lessThanOrEqualTo(2));
      });
    });

    test("a re-read from account A landing after B signed in doesn't show "
        "A's plan", () {
      return run(() async {
        backend.holdDaily = true;
        outfits().updateOutfitFavorite(2, isFavorite: true); // A's re-read
        await _settle();
        final aGates = [...backend._heldDaily];
        backend._heldDaily.clear();

        // B signs in: both providers rebuild for the new account.
        setUpFakeAuth(accessToken: 'token-b');
        backend
          ..token = 'B'
          ..holdDaily = false;
        container
          ..invalidate(outfitsProvider)
          ..invalidate(dailyOutfitProvider);
        await _settle();
        expect(container.read(dailyOutfitProvider).value!.first.name, 'B-plan');

        for (final g in aGates) {
          g.complete();
        }
        await _settle();
        expect(container.read(dailyOutfitProvider).value!.first.name, 'B-plan');
      });
    });
  });

  group('D3: generations', () {
    /// Starts an outfits-triggered re-read for the current account and
    /// returns its held GET.
    // A re-read trigger that still is one: a version delete (an id unknown
    // to the backend's fake, so nothing actually goes).
    var deletes = 0;
    Future<void> triggerResync() =>
        OutfitService().deleteOutfit(99, 9000 + deletes++);

    Future<Completer<void>> heldResync(int outfitId) async {
      backend.holdDaily = true;
      await triggerResync();
      await _settle();
      expect(
        backend._heldDaily,
        isNotEmpty,
        reason: "this account's re-read was sent",
      );
      final gate = backend._heldDaily.removeLast();
      backend.holdDaily = false;
      return gate;
    }

    /// Signs [account] in: both providers rebuild for it.
    Future<void> signIn(String account) async {
      setUpFakeAuth(accessToken: 'token-${account.toLowerCase()}');
      backend.token = account;
      container
        ..invalidate(outfitsProvider)
        ..invalidate(dailyOutfitProvider);
      await _settle();
    }

    String? planName() => container.read(dailyOutfitProvider).value!.first.name;

    for (final order in [
      [0, 1],
      [1, 0],
    ]) {
      test('A → B → C, the late re-reads answering ${order.join('→')}: C '
          'keeps its plan', () {
        return run(() async {
          final gates = [await heldResync(2)];
          await signIn('B');
          gates.add(await heldResync(2));
          await signIn('C');
          expect(planName(), 'C-plan');

          for (final i in order) {
            gates[i].complete();
            await _settle();
          }
          expect(planName(), 'C-plan');
          expect(container.read(dailyOutfitProvider).hasError, isFalse);
        });
      });
    }

    test("the new account's re-read starts while the old one's is still in "
        'flight', () {
      return run(() async {
        final aGate = await heldResync(2);
        await signIn('B');
        final before = backend.dailyGets;

        await triggerResync();
        await _settle();

        expect(backend.dailyGets, before + 1, reason: "B's own re-read");
        aGate.complete();
        await _settle();
      });
    });

    test("the old re-read finishing doesn't clear the new one's sync state "
        '(a further change still coalesces)', () {
      return run(() async {
        final aGate = await heldResync(2);
        await signIn('B');
        final bGate = await heldResync(2); // B's re-read, in flight
        backend.holdDaily = true;

        aGate.complete(); // A's finishes
        await _settle();
        final before = backend.dailyGets;
        await triggerResync();
        await _settle();
        expect(
          backend.dailyGets,
          before,
          reason: 'coalesced into B\'s pending pass, not a parallel GET',
        );

        bGate.complete();
        await backend.releaseDaily(); // B's follow-up pass
        expect(planName(), 'B-plan');
      });
    });

    test("an old re-read failing after the switch doesn't error the new "
        'account', () {
      return run(() async {
        backend.failNextDaily = true;
        final aGate = await heldResync(2);
        await signIn('B');

        aGate.complete();
        await _settle();
        expect(container.read(dailyOutfitProvider).hasError, isFalse);
        expect(planName(), 'B-plan');
      });
    });

    test("an old re-read finding no plan doesn't go on to generate (with "
        "the new account's outfits) after the switch", () {
      backend.emptyPlanFor.add('A');
      return run(() async {
        final generatesBefore = backend.generates;
        final aGate = await heldResync(2); // A's day: no plan
        await signIn('B'); // B has a plan
        expect(planName(), 'B-plan');

        aGate.complete();
        await _settle();
        expect(
          backend.generates,
          generatesBefore,
          reason: 'generated: ${backend.generatedBy}',
        );
        expect(planName(), 'B-plan');
      });
    });

    test('a refresh() from the old account landing after the switch '
        "doesn't replace the new account's plan", () {
      return run(() async {
        backend.holdDaily = true;
        final refresh = container.read(dailyOutfitProvider.notifier).refresh();
        await _settle();
        final aGate = backend._heldDaily.removeLast();
        backend.holdDaily = false;
        await signIn('B');

        aGate.complete();
        await refresh;
        await _settle();
        expect(planName(), 'B-plan');
      });
    });
  });

  group('D1/D2: what still syncs', () {
    Outfit? inDaily(int id) {
      for (final o in container.read(dailyOutfitProvider).value!) {
        if (o.id == id) return o;
      }
      return null;
    }

    test("regenerating a non-card version in the plan updates today's card "
        'with no outfits refresh at all (e.g. it lands after the user left '
        'Outfit Details)', () {
      return run(() async {
        await OutfitService().regenerateOutfit(1, 11);
        await _settle();

        expect(inDaily(11)?.resultImageCacheKey, '11-r1');
      });
    });

    test('regenerating an outfit that is not in the plan re-reads nothing', () {
      return run(() async {
        final gets = await dailyGetsDuring(
          () => OutfitService().regenerateOutfit(2, 2),
        );
        expect(gets, 0);
      });
    });

    test('the same outfit reported regenerated several times in a burst '
        'costs at most two re-reads', () {
      return run(() async {
        backend.holdRegenerate = true;
        final renders = [
          for (var i = 0; i < 3; i++) OutfitService().regenerateOutfit(1, 11),
        ];
        await _settle();
        backend.holdRegenerate = false;
        final gets = await dailyGetsDuring(() async {
          for (final g in backend.heldRegenerates) {
            g.complete();
          }
          await Future.wait(renders);
        });

        expect(gets, inInclusiveRange(1, 2));
        expect(inDaily(11)?.resultImageCacheKey, startsWith('11-r'));
      });
    });

    test('a new version added to an existing group (the card list unchanged) '
        'still lets a day with too few outfits generate', () {
      backend
        ..plan = []
        ..minCandidates = 4; // 3 candidates now: insufficient
      return run(() async {
        expect(daily(), isEmpty);
        backend.minCandidates = 4;
        final before = backend.generates;

        await OutfitService().generateOutfit(garmentIds: [1, 2], groupId: 1);
        await outfits().refresh(); // the card list is the same
        await _settle();

        expect(backend.generates, greaterThan(before));
        expect(daily(), isNotEmpty);
      });
    });

    test('a burst of real triggers coalesces into at most two re-reads', () {
      return run(() async {
        backend.holdDaily = true;
        final gets = await dailyGetsDuring(() async {
          await OutfitService().deleteOutfit(99, 9101);
          await OutfitService().deleteOutfit(99, 9102);
          await OutfitService().regenerateOutfit(1, 11);
          outfits().removeGroup(2); // a card change too
          await _settle();
          await backend.releaseDaily();
        });
        expect(gets, lessThanOrEqualTo(2));
      });
    });

    test("account A's regenerate finishing after B signed in doesn't make B "
        're-read', () {
      return run(() async {
        backend.holdRegenerate = true;
        final render = OutfitService().regenerateOutfit(1, 11); // A's
        await _settle();

        setUpFakeAuth(accessToken: 'token-b');
        backend
          ..token = 'B'
          ..plan = [2]; // B's plan
        container
          ..invalidate(outfitsProvider)
          ..invalidate(dailyOutfitProvider);
        await _settle();

        backend.holdRegenerate = false;
        final gets = await dailyGetsDuring(() async {
          for (final g in backend.heldRegenerates) {
            g.complete();
          }
          await render;
        });
        expect(gets, 0);
      });
    });
  });

  // Final concurrency audit: a manual refresh() (Home's pull-to-refresh,
  // refreshIfNeeded) in flight while the events that drive a re-read
  // arrive. _syncWithOutfits returns at once while state.isLoading, and
  // nothing remembers that it did. Skipped tests reproduce a finding.
  group('refresh() vs. events', () {
    DailyOutfitNotifier notifier() =>
        container.read(dailyOutfitProvider.notifier);
    AsyncValue<List<Outfit>> state() => container.read(dailyOutfitProvider);

    /// A refresh whose GET has reached the server (answering with the plan
    /// as it is now) and is held there.
    Future<({Future<void> done})> heldRefresh() async {
      backend.holdDaily = true;
      final done = notifier().refresh();
      await _settle();
      expect(backend._heldDaily, hasLength(1));
      return (done: done);
    }

    Future<void> answerRefresh(Future<void> done) async {
      await backend.releaseDaily();
      await done;
      await _settle();
    }

    Outfit? planned(int id) {
      for (final o in state().value ?? const <Outfit>[]) {
        if (o.id == id) return o;
      }
      return null;
    }

    /// Answers whatever daily GETs are held, newest first, until none are
    /// left (follow-up passes are held too): the worst order for an older
    /// answer that would overwrite a newer one.
    Future<void> answerNewestFirst() async {
      while (backend._heldDaily.isNotEmpty) {
        final gate = backend._heldDaily.removeLast();
        gate.complete();
        await _settle();
      }
      backend.holdDaily = false;
      await _settle();
    }

    test('R1a. deleting a planned outfit during a refresh still leaves it '
        'out of the plan', () {
      return run(() async {
        final r = (await heldRefresh()).done;
        await OutfitService().deleteGroup(1); // planned: 1 and 11
        outfits().removeGroup(1);
        await _settle();

        await answerRefresh(r);
        expect(planned(1), isNull);
        expect(planned(11), isNull);
      });
    });

    test('R1b. deleting a planned non-card version during a refresh', () {
      return run(() async {
        final r = (await heldRefresh()).done;
        await OutfitService().deleteOutfit(1, 11);
        outfits().removeOutfitVersion(11);
        await _settle();

        await answerRefresh(r);
        expect(planned(11), isNull);
      });
    });

    test("R1c. a planned card re-rendered during a refresh shows its new "
        "image", () {
      return run(() async {
