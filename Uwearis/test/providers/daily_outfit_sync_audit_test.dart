  group('refresh() semantics', () {
    DailyOutfitNotifier notifier() =>
        container.read(dailyOutfitProvider.notifier);
    AsyncValue<List<Outfit>> state() => container.read(dailyOutfitProvider);

    test('with no events, a refresh costs exactly one GET', () {
      return run(() async {
        final before = backend.dailyGets;
        await notifier().refresh();
        await _settle();
        expect(backend.dailyGets - before, 1);
        expect(state().value!.map((o) => o.id), [1, 11]);
      });
    });

    test('a refresh is loading until its answer, keeping the plan shown', () {
      return run(() async {
        backend.holdDaily = true;
        final r = notifier().refresh();
        await _settle();
        expect(state().isLoading, isTrue);
        expect(state().value!.map((o) => o.id), [1, 11]);

        await backend.releaseDaily();
        await r;
        expect(state().isLoading, isFalse);
      });
    });

    test('a failed refresh with no events is an error keeping the plan', () {
      return run(() async {
        backend.failNextDaily = true;
        await notifier().refresh();
        await _settle();
        expect(state().hasError, isTrue);
        expect(state().value!.map((o) => o.id), [1, 11]);
      });
    });

    test("a refresh's Future completes only after the follow-up pass for an "
        'event that arrived during it', () {
      return run(() async {
        backend.holdDaily = true;
        var done = false;
        final r = notifier().refresh().then((_) => done = true);
        await _settle();
        await OutfitService().deleteOutfit(1, 11);
        await _settle();

        backend._heldDaily.removeAt(0).complete(); // the refresh's own GET
        await _settle();
        expect(done, isFalse, reason: 'the follow-up pass is still running');

        await backend.releaseDaily();
        await r;
        expect(state().value!.map((o) => o.id), [1]);
      });
    });

    test('a refresh joining a running re-read sends no parallel GET', () {
      return run(() async {
        backend.holdDaily = true;
        await OutfitService().deleteOutfit(99, 9601); // a re-read, held
        await _settle();
        final r = notifier().refresh();
        await _settle();
        expect(backend._heldDaily, hasLength(1));

        await backend.releaseDaily();
        await r;
      });
    });

    test('A → B → C with events pending in A and B: C gets only its own '
        'load', () {
      return run(() async {
        Future<void> signIn(String account) async {
          setUpFakeAuth(accessToken: 'token-${account.toLowerCase()}');
          backend.token = account;
          container
            ..invalidate(outfitsProvider)
            ..invalidate(dailyOutfitProvider);
          await _settle();
        }

        backend.holdDaily = true;
        final a = notifier().refresh(); // A's refresh, held
        await _settle();
        await OutfitService().deleteOutfit(99, 9701); // pending in A
        await signIn('B'); // B's load, held
        await OutfitService().deleteOutfit(99, 9702); // pending in B
        backend.holdDaily = false;
        await signIn('C');
        final before = backend.dailyGets;

        await answerAll();
        await a;
        await _settle();
        expect(backend.dailyGets, before, reason: 'no follow-up for A or B');
        expect(state().value!.first.name, 'C-plan');
      });
    });
